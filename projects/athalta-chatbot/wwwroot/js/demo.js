let demoIndex = 0;
let demoCurrent = null;
let demoNoticeShown = false;

function getDemoQuestion() {
    demoCurrent = DEMO_QUESTIONS[demoIndex % DEMO_QUESTIONS.length];
    demoIndex++;

    let content = demoCurrent.question;
    if (!demoNoticeShown) {
        demoNoticeShown = true;
        content = `<div class="demo-notice">מצב הדגמה: גרסה זו מוצגת ללא שרת, ולכן השאלות והמשוב מוכנים מראש. בגרסה המלאה השאלות, התמונות והמשוב נוצרים על ידי OpenAI.</div>` + content;
    }
    return { content: content, imageUrl: null };
}

function getDemoFeedback(userText) {
    if (!demoCurrent) {
        return "לחצו על \"המשך תרגול\" כדי לקבל שאלה.";
    }
    const hits = demoCurrent.keywords.filter(k => userText.includes(k));
    const opening = hits.length > 0
        ? "כל הכבוד! התשובה שלך נוגעת בנקודות המרכזיות."
        : "תודה על התשובה! כדאי להרחיב מעט.";
    return `${opening}\n\nתשובה מלאה: ${demoCurrent.answer}`;
}
